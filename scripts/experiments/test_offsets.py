def get_offsets(n):
    if n == 1: return [(0,0)]
    if n == 2: return [(-6,0), (6,0)]
    if n == 3: return [(-6,6), (0,-6), (6,0)]
    if n == 4: return [(-6,-6), (6,-6), (-6,6), (6,6)]
    if n == 5: return [(0,0), (-6,-6), (6,-6), (-6,6), (6,6)]
    if n == 6: return [(-6,0), (6,0), (0,-6), (0,6), (-6,6), (6,-6)]
    if n == 7: return [(0,0), (-6,0), (6,0), (0,-6), (0,6), (-6,6), (6,-6)]
    if n == 8: return [(-6,-6), (6,-6), (-6,6), (6,6), (-12,0), (12,0), (0,-12), (0,12)]
    if n == 9: return [(0,0), (-6,-6), (6,-6), (-6,6), (6,6), (-12,0), (12,0), (0,-12), (0,12)]
    if n == 10: return [(-6,-6), (6,-6), (-6,6), (6,6), (-12,0), (12,0), (0,-12), (0,12), (-12,-12), (12,12)] # sum = 0,0

for n in range(1, 11):
    offs = get_offsets(n)
    sum_x = sum(o[0] for o in offs)
    sum_y = sum(o[1] for o in offs)
    print(f"N={n}, sum=({sum_x},{sum_y}), distinct={len(set(offs)) == n}")
