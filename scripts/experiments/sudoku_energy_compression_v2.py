"""Energy COMPRESSION test on Sudoku-Extreme (the v1 follow-up).

Human-seeded thesis (operator 2026-06-05) — see
docs/research-notes/energy-as-generator-sudoku-thesis.md +
memory project_energy_as_generator_sudoku.

v1 finding: a contrastive EBT trained with LOCAL negatives (corruptions of each
gold solution) became a near-PERFECT SCORER (loss 0.0001, gap ~17) but a FAILED
GENERATOR (decode 0.000, worse than random). DIAGNOSIS (Kona's "energy compression"
framing): we never restricted the GLOBAL low-energy VOLUME, so broad low-energy
"hallucinated flatlands" existed far from any solution, and energy-descent drifted
into them. The fix energy compression prescribes: push energy UP at the model's own
low-energy regions (small partition function Z), so the only low-energy basins are
the true solutions.

This harness changes ONE variable from v1: NEGATIVE SAMPLING. Instead of local
corruptions, negatives are generated by LANGEVIN / persistent contrastive
divergence (PCD) — short-run gradient descent (+noise) on the energy from a
persistent buffer, i.e. the model's *current* low-energy samples. Contrastive-
divergence loss then pushes those up and the gold down → carves the global
landscape (compresses the low-energy volume). Plus an anti-collapse energy-
magnitude regularizer. Decode = annealed Langevin descent (same procedure as
training-negative generation → train/inference consistency).

INSTRUMENTED: logs the EBT energy of DECODED grids vs GOLD grids. Prediction —
v1-style (uncompressed): decoded garbage has LOWER energy than gold (flatland
smoking gun). v2 (compressed): decoded energy should rise ABOVE gold and decode
solve-rate should climb from ~0 toward/past the refiner's 0.182.

GPU: INTERNAL RTX 3090 only (CUDA_VISIBLE_DEVICES=GPU-7971baff-...). Conductor PAUSED.
"""
from __future__ import annotations
import argparse, json, os, sys, time
from pathlib import Path
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sudoku_energy_vs_ar_v1 import (  # reuse the proven pieces
    load_split, EBT, gold_digits, sudoku_violations,
    VOCAB, SEQ, BLANK, DIGIT0, N_DIGITS,
)


def clamp_givens(soft, xb):
    """soft: (B,81,9) probs; clamp given cells to their true one-hot."""
    blanks = (xb == BLANK)
    given_oh = F.one_hot(gold_digits(xb).clamp(0, 8), N_DIGITS).float()
    return torch.where(blanks[..., None], soft, given_oh)


def langevin(model, xb, L, steps, step_size, noise, temp=1.0):
    """In-place-ish Langevin descent on logits L (B,81,9) minimising E. Givens are
    clamped via clamp_givens. Returns the final detached L. Each step uses a fresh
    grad (no graph accumulation across steps)."""
    for _ in range(steps):
        L = L.detach().requires_grad_(True)
        soft = clamp_givens(F.softmax(L / temp, -1), xb)
        e = model(xb, soft).sum()
        (g,) = torch.autograd.grad(e, L)
        L = L - step_size * g + noise * torch.randn_like(L)
    return L.detach()


def train_ebt_cd(args, device):
    xtr, ytr = load_split("train", args.train_n, args.seed)
    xev, yev = load_split("test", args.eval_n, args.seed + 1)
    model = EBT(args.hidden, args.layers, args.heads).to(device)
    nparams = sum(p.numel() for p in model.parameters())
    opt = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=0.01, betas=(0.9, 0.95))
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, args.lr, total_steps=args.steps, pct_start=0.1)
    model.train(); n = xtr.shape[0]; t0 = time.time()
    # persistent buffer of negatives (PCD), one slot per a rotating pool
    buf = torch.randn(args.buffer, SEQ, N_DIGITS, device=device)
    for step in range(args.steps):
        idx = torch.randint(0, n, (args.batch,))
        xb = xtr[idx].to(device); yd = gold_digits(ytr[idx].to(device))
        # --- draw negatives from the persistent buffer; reinit a fraction (diversity)
        bsel = torch.randint(0, args.buffer, (args.batch,), device=device)
        L0 = buf[bsel].clone()
        reinit = (torch.rand(args.batch, device=device) < args.reinit_frac)
        L0[reinit] = torch.randn_like(L0[reinit])
        # --- Langevin / PCD negative generation (no grad to params)
        with torch.enable_grad():
            Lneg = langevin(model, xb, L0, args.k_langevin, args.lang_step, args.lang_noise)
        buf[bsel] = Lneg.detach()                              # persist
        # --- contrastive-divergence loss (grad to params)
        soft_neg = clamp_givens(F.softmax(Lneg, -1), xb)
        gold_oh = F.one_hot(yd, N_DIGITS).float()
        e_gold = model(xb, clamp_givens(gold_oh, xb))
        e_neg = model(xb, soft_neg)
        cd = (e_gold.mean() - e_neg.mean())                   # push gold down, neg up
        reg = args.alpha * (e_gold ** 2 + e_neg ** 2).mean()  # restrict energy volume (anti-collapse)
        loss = cd + reg
        opt.zero_grad(); loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0); opt.step(); sched.step()
        if step % args.log_every == 0 or step == args.steps - 1:
            print(f"[ebt-cd] step={step} loss={loss.item():.4f} cd={cd.item():.4f} "
                  f"e_gold={e_gold.mean().item():.3f} e_neg={e_neg.mean().item():.3f} "
                  f"t={time.time()-t0:.0f}s", flush=True)
    metrics = evaluate(model, xev, yev, device, args)
    metrics.update({"n_params": nparams, "train_seconds": time.time() - t0})
    return model, metrics


@torch.no_grad()
def _energy_of(model, xb, digit_grid):
    return model(xb, digit_grid).detach()


def decode_anneal(model, xb, args):
    """Annealed Langevin decode: descend energy from random init, lowering noise."""
    B = xb.shape[0]
    L = torch.randn(B, SEQ, N_DIGITS, device=xb.device)
    n = args.decode_steps
    for i in range(n):
        frac = i / max(1, n - 1)
        noise = args.decode_noise0 * (1 - frac)               # anneal noise -> 0
        with torch.enable_grad():
            L = langevin(model, xb, L, 1, args.decode_step, noise, temp=max(0.3, 1 - frac))
    blanks = (xb == BLANK)
    out = torch.where(blanks, F.softmax(L, -1).argmax(-1), gold_digits(xb).clamp(0, 8))
    return out


@torch.no_grad()
def evaluate(model, xev, yev, device, args, bs=128):
    model.eval(); n = xev.shape[0]
    hits = 0; blank_correct = 0.0; blank_total = 0.0; viol = 0
    e_dec_sum = 0.0; e_gold_sum = 0.0; n_seen = 0
    for i in range(0, n, bs):
        xb = xev[i:i + bs].to(device); yd = gold_digits(yev[i:i + bs].to(device))
        with torch.enable_grad():
            pred = decode_anneal(model, xb, args)
        blanks = (xb == BLANK); blank_total += blanks.float().sum().item()
        hits += (pred == yd).all(-1).sum().item()
        blank_correct += ((pred == yd) & blanks).float().sum().item()
        viol += sudoku_violations(pred).sum().item()
        # diagnostic: energy of decoded grid vs gold grid
        e_dec_sum += _energy_of(model, xb, pred).sum().item()
        e_gold_sum += _energy_of(model, xb, yd).sum().item()
        n_seen += xb.shape[0]
    return {
        "ebt_cd_solve_rate": hits / n,
        "ebt_cd_blank_cell_acc": blank_correct / max(1, blank_total),
        "ebt_cd_mean_violations": viol / n,
        "decoded_grid_mean_energy": e_dec_sum / n_seen,
        "gold_grid_mean_energy": e_gold_sum / n_seen,
        "flatland_diagnostic": ("CARVED: decoded energy ABOVE gold (compression worked)"
                                if e_dec_sum > e_gold_sum else
                                "FLATLAND: decoded energy BELOW/equal gold (low-energy garbage — compression insufficient)"),
        "n_eval": n,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--steps", type=int, default=10000)
    ap.add_argument("--batch", type=int, default=64)
    ap.add_argument("--hidden", type=int, default=256)
    ap.add_argument("--layers", type=int, default=4)
    ap.add_argument("--heads", type=int, default=4)
    ap.add_argument("--lr", type=float, default=2e-4)
    ap.add_argument("--train_n", type=int, default=400000)
    ap.add_argument("--eval_n", type=int, default=500)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--log_every", type=int, default=500)
    # Langevin / PCD negatives (the energy-compression knobs)
    ap.add_argument("--k_langevin", type=int, default=20)     # Langevin steps per training neg
    ap.add_argument("--lang_step", type=float, default=1.0)   # Langevin step size
    ap.add_argument("--lang_noise", type=float, default=0.1)  # Langevin noise
    ap.add_argument("--buffer", type=int, default=10000)      # PCD persistent buffer size
    ap.add_argument("--reinit_frac", type=float, default=0.05)
    ap.add_argument("--alpha", type=float, default=0.1)       # anti-collapse energy reg
    # decode (annealed Langevin)
    ap.add_argument("--decode_steps", type=int, default=300)
    ap.add_argument("--decode_step", type=float, default=1.0)
    ap.add_argument("--decode_noise0", type=float, default=0.3)
    ap.add_argument("--out", default="results/sudoku_ebt_compression_v2.json")
    args = ap.parse_args()

    torch.manual_seed(args.seed); np.random.seed(args.seed)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"device={device} cuda_devices={torch.cuda.device_count()}", flush=True)
    assert device == "cuda", "refusing to run on CPU — pin the internal 3090"

    _, metrics = train_ebt_cd(args, device)
    metrics.update({"model": "ebt_compression_cd", "args": vars(args),
                    "gpu": torch.cuda.get_device_name(0)})
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    json.dump(metrics, open(args.out, "w"), indent=2)
    print(json.dumps({k: v for k, v in metrics.items() if k != "args"}, indent=2), flush=True)


if __name__ == "__main__":
    main()
