def main(argv: list[str] | None = None) -> int:  # pragma: no cover
    """CLI entry point for Exp 282.

    Environment variables
    ---------------------
    CARNOT_FORCE_LIVE : Set to ``"1"`` for live GPU execution, ``"0"`` for mock.
    JAX_PLATFORMS     : Set to ``"cpu"`` to prevent JAX from claiming the GPU.

    Returns:
        Exit code (0 = success).
    """
    import argparse

    parser = argparse.ArgumentParser(
        description=f"Exp {EXPERIMENT}: GPU baseline on Apple adversarial GSM8K corpus",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--dataset",
        type=Path,
        default=_DATASET_PATH,
        help="Path to gsm8k_adversarial_281.jsonl",
    )
    parser.add_argument(
        "--checkpoint-dir",
        type=Path,
        default=_CHECKPOINT_BASE,
        help="Directory for per-(model, variant) checkpoint files.",
    )
    parser.add_argument(
        "--logit-dir",
        type=Path,
        default=_LOGIT_BASE,
        help="Directory for logit .npy files.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=_OUTPUT_PATH,
        help="Destination JSON path for the experiment artifact.",
    )
    args = parser.parse_args(argv)

    # Load dataset.
    if not args.dataset.exists():
        print(f"[Exp {EXPERIMENT}] ERROR: dataset not found at {args.dataset}")
        return 1

    rows: list[dict[str, Any]] = [
        json.loads(line)
        for line in args.dataset.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    print(f"[Exp {EXPERIMENT}] Loaded {len(rows)} rows from {args.dataset}")

    runner = AppleBaselineRunner(
        rows=rows,
        checkpoint_dir=args.checkpoint_dir,
        logit_dir=args.logit_dir,
    )

    print(f"[Exp {EXPERIMENT}] Starting baseline inference "
          f"(CARNOT_FORCE_LIVE={os.environ.get('CARNOT_FORCE_LIVE', '0')})…")
    artifact = runner.run_with_timeout_handling(
        output_path=args.output,
        inference_mode=(
            "live_gpu" if os.environ.get("CARNOT_FORCE_LIVE", "0") == "1" else "mock"
        ),
    )

    _print_report(artifact)
    print(f"[Exp {EXPERIMENT}] Artifact written to {args.output}")
    return 0


