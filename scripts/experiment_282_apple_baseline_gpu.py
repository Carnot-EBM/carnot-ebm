def _logit_npy_path(logit_dir: Path, *, model_name: str, variant_type: str, pct: int) -> Path:
    """Return the .npy path for the logit tensor at a given prefix fraction.

    File naming: ``logits_282_{model_slug}_{variant}_{pct}pct.npy``

    Args:
        logit_dir: Base directory for logit files.
        model_name: Human-readable model label.
        variant_type: Question variant (``"standard"`` / ``"number_swap"`` / ``"irrelevant_sentence"``).
        pct: Percentage value (25, 50, 75, or 100).

    Returns:
        Absolute .npy path.
    """
    fname = f"logits_282_{safe_slug(model_name)}_{safe_slug(variant_type)}_{pct}pct.npy"
    return logit_dir / fname


def _save_logits(
    logit_dir: Path,
    *,
    model_name: str,
    variant_type: str,
    pct: int,
    logit_list: list[np.ndarray],
) -> str:
    """Stack *logit_list* into an object array and save as .npy.

    Each element of *logit_list* is a ``(1, seq_len, vocab_size)`` array.  We
    store them as a 1-D NumPy object array (ragged rows permitted by variable
    ``seq_len``) so callers can retrieve individual question logits by index.

    Args:
        logit_dir: Destination directory.
        model_name: Model label — used in filename.
        variant_type: Variant label — used in filename.
        pct: Fraction label (25 / 50 / 75 / 100) — used in filename.
        logit_list: List of per-question logit arrays (may have varying seq_len).

    Returns:
        String path of the saved file (for inclusion in the artifact).
    """
    logit_dir.mkdir(parents=True, exist_ok=True)
    out_path = _logit_npy_path(logit_dir, model_name=model_name, variant_type=variant_type, pct=pct)

    # Use an object array to accommodate variable sequence lengths.
    arr = np.empty(len(logit_list), dtype=object)
    for i, logits in enumerate(logit_list):
        # Strip the leading batch dimension: (1, seq_len, vocab_size) → (seq_len, vocab_size).
        arr[i] = logits[0] if logits.ndim == 3 else logits
    np.save(str(out_path), arr, allow_pickle=True)
    return str(out_path)


