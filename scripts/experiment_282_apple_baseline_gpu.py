class AppleBaselineRunner:
    """Run baseline inference on the Apple adversarial GSM8K corpus.

    This class is the central controller for Exp 282.  It:

    1. Accepts a list of rows from the Exp 281 dataset (each row has both
       ``original_question`` and ``variant_question``).
    2. Builds three virtual question sets per model: ``standard``
       (original questions), ``number_swap`` (variant questions from
       number_swap rows), and ``irrelevant_sentence`` (variant questions from
       irrelevant_sentence rows).
    3. Runs baseline inference via an injectable ``generate_fn`` (real GPU
       model in live mode; a fake callable in unit tests).
    4. Saves logit tensors at 25 / 50 / 75 / 100 % prefix fractions.
    5. Writes a checkpoint every ``CHECKPOINT_INTERVAL`` questions so long
       runs can be resumed after interruption.
    6. Handles ``TimeoutError`` from ``generate_fn`` by emitting a partial
       artifact with a ``stall_at`` field.

    Args:
        rows: List of dicts loaded from ``gsm8k_adversarial_281.jsonl``.
        model_specs: Ordered list of ``{"name": ..., "gpu": int}`` dicts.
                     Defaults to ``MODEL_SPECS`` (Qwen GPU 0, Gemma GPU 1).
        generate_fn: Callable ``(question, expected_answer, *, model_name, variant_type) ->
                     (response_str, logit_ndarray)``.  Injected in tests.
        checkpoint_dir: Directory for per-(model, variant) checkpoint files.
        logit_dir: Directory where logit .npy files are saved.
        timeout_seconds: Per-call hard timeout in seconds.  Defaults to
                         ``INFERENCE_TIMEOUT_SECONDS`` (60 s).
    """

    def __init__(
        self,
        rows: list[dict[str, Any]],
        *,
        model_specs: list[dict[str, Any]] | None = None,
        generate_fn: Callable[..., tuple[str, np.ndarray]] | None = None,
        checkpoint_dir: Path | None = None,
        logit_dir: Path | None = None,
        timeout_seconds: int = INFERENCE_TIMEOUT_SECONDS,
    ) -> None:
        self.rows = list(rows)
        self.model_specs: list[dict[str, Any]] = list(model_specs or MODEL_SPECS)
        self.generate_fn = generate_fn or self._default_generate_fn()
        self.checkpoint_dir: Path = checkpoint_dir or _CHECKPOINT_BASE
        self.logit_dir: Path = logit_dir or _LOGIT_BASE
        self.timeout_seconds = timeout_seconds

        # Model results collected across all variants: {model_name: {variant: {…}}}
        self._model_results: dict[str, dict[str, Any]] = {}
        # Logit paths collected across all variants: {model_name: {fraction_label: path}}
        self._logit_paths: dict[str, dict[str, str]] = {}

        # DualGPURunner is wired at construction time so GPU slots are reserved
        # immediately, before any data loading or inference starts.
        # In mock mode (CARNOT_FORCE_LIVE=0) this is skipped to avoid importing torch.
        self._dual_runner: Any | None = None
        if os.environ.get("CARNOT_FORCE_LIVE", "0") == "1":
            self._wire_dual_gpu_runner()

    # ------------------------------------------------------------------
    # DualGPU wiring (live mode only)
    # ------------------------------------------------------------------

    def _wire_dual_gpu_runner(self) -> None:
        """Wire the DualGPURunner at startup so GPU slots are reserved early.

        Assigns Qwen to GPU 0 and Gemma to GPU 1 matching the MODEL_SPECS
        ordering (SCENARIO-VERIFY-082).  Prints a confirmation line so the
        operator can verify GPU assignments in the run log.
        """
        try:
            import sys
            import importlib.util as ilu

            harness_path = Path(__file__).parent / "experiment_258_dual_gpu_harness.py"
            spec258 = ilu.spec_from_file_location("experiment_258_dual_gpu_harness", harness_path)
            assert spec258 is not None and spec258.loader is not None
            mod258 = ilu.module_from_spec(spec258)
            spec258.loader.exec_module(mod258)  # type: ignore[union-attr]

            harness = mod258.DualGPUBenchmarkHarness(
                model_specs=[
                    {"name": s["name"], "hf_id": s.get("hf_id", s["name"])}
                    for s in self.model_specs
                ]
            )
            harness.verify_gpu_assignments()
            self._dual_runner = harness
            print(f"[Exp 282] DualGPURunner wired:")
            for i, spec in enumerate(self.model_specs):
                print(f"  GPU {spec.get('gpu', i)}: {spec['name']}")
        except Exception as exc:  # noqa: BLE001
            print(f"[Exp 282] DualGPURunner unavailable ({exc}) — proceeding without GPU runner")

    # ------------------------------------------------------------------
    # Default generate fn (live GPU mode)
    # ------------------------------------------------------------------

    @staticmethod
    def _default_generate_fn() -> Callable[..., tuple[str, np.ndarray]]:
        """Return the live GPU inference function.

        In live mode (``CARNOT_FORCE_LIVE=1``) this loads the transformers
        pipeline for the specified model and runs a greedy decode, capturing
        the full logit tensor for later analysis.

        Returns:
            Callable ``(question, expected_answer, *, model_name, variant_type)
            -> (response_text, logits_ndarray)`` where ``logits_ndarray`` has
            shape ``(1, seq_len, vocab_size)``.
        """
        if os.environ.get("CARNOT_FORCE_LIVE", "0") != "1":
            # Mock fallback: always return the correct answer with a dummy logit.
            def _mock(question: str, expected_answer: int, **kw: Any) -> tuple[str, np.ndarray]:
                logits = np.zeros((1, 8, 100), dtype=np.float32)
                return str(expected_answer), logits
            return _mock

        try:
            import torch
            from transformers import AutoModelForCausalLM, AutoTokenizer

            _model_cache: dict[str, Any] = {}

            def _live(question: str, expected_answer: int, *, model_name: str = "Qwen3.5-0.8B", variant_type: str = "standard", **kw: Any) -> tuple[str, np.ndarray]:
                """Live GPU inference: greedy decode with logit capture."""
                # Look up HF model id from MODEL_SPECS.
                hf_id = next(
                    (s.get("hf_id", s["name"]) for s in MODEL_SPECS if s["name"] == model_name),
                    model_name,
                )
                gpu_id = next(
                    (s.get("gpu", 0) for s in MODEL_SPECS if s["name"] == model_name),
                    0,
                )
                device = f"cuda:{gpu_id}" if torch.cuda.is_available() else "cpu"

                if hf_id not in _model_cache:
                    tokenizer = AutoTokenizer.from_pretrained(hf_id)
                    model = AutoModelForCausalLM.from_pretrained(hf_id, torch_dtype=torch.float16)
                    model = model.to(device).eval()
                    _model_cache[hf_id] = (model, tokenizer)

                model, tokenizer = _model_cache[hf_id]
                prompt = (
                    f"Solve the following math problem step by step. "
                    f"State the final answer as a single number.\n\n"
                    f"Problem: {question}\n\nAnswer:"
                )
                inputs = tokenizer(prompt, return_tensors="pt").to(device)
                with torch.no_grad():
                    output = model.generate(
                        **inputs,
                        max_new_tokens=256,
                        do_sample=False,
                        output_scores=True,
                        return_dict_in_generate=True,
                    )
                # Decode the response text.
                generated_ids = output.sequences[0][inputs["input_ids"].shape[1]:]
                response = tokenizer.decode(generated_ids, skip_special_tokens=True)

                # Stack per-token score tensors: (generated_len, vocab_size) → (1, seq_len, vocab_size).
                if output.scores:
                    logits_2d = torch.stack(output.scores, dim=0).cpu().float().numpy()
                    logits = np.expand_dims(logits_2d, axis=0)  # (1, seq_len, vocab_size)
                else:
                    logits = np.zeros((1, 1, model.config.vocab_size), dtype=np.float32)

                return response, logits

            return _live

        except ImportError as exc:
            raise RuntimeError(
                f"[Exp 282] Live inference requires 'torch' and 'transformers' but import failed: {exc}"
            ) from exc

    # ------------------------------------------------------------------
    # Dataset helpers
    # ------------------------------------------------------------------

    def _build_variant_questions(self, variant_type: str) -> list[dict[str, Any]]:
        """Build the question list for one variant type.

        For ``"standard"`` we use ``original_question`` / ``original_answer`` from
        every row (de-duplicated by ``question_id`` since each question appears in
        both the number_swap and irrelevant_sentence rows).

        For ``"number_swap"`` and ``"irrelevant_sentence"`` we use
        ``variant_question`` / ``variant_answer`` from rows of the matching type.

        Args:
            variant_type: One of ``"standard"``, ``"number_swap"``,
                          ``"irrelevant_sentence"``.

        Returns:
            List of ``{"question_id", "question", "expected_answer"}`` dicts.
        """
        if variant_type == "standard":
            seen: set[str] = set()
            out: list[dict[str, Any]] = []
            for row in self.rows:
                qid = row["question_id"]
                if qid not in seen:
                    seen.add(qid)
                    out.append({
                        "question_id": qid,
                        "question": row["original_question"],
                        "expected_answer": row["original_answer"],
                    })
            return out

        return [
            {
                "question_id": row["question_id"],
                "question": row["variant_question"],
                "expected_answer": row["variant_answer"],
            }
            for row in self.rows
            if row.get("variant_type") == variant_type
        ]

    # ------------------------------------------------------------------
    # Core inference loop
    # ------------------------------------------------------------------

    def run_variant(
        self,
        *,
        model_name: str,
        variant_type: str,
    ) -> list[dict[str, Any]]:
        """Run baseline inference for one (model, variant_type) pair.

        Checkpoints every ``CHECKPOINT_INTERVAL`` questions.  Saves logit
        tensors at prefix fractions defined by ``LOGIT_FRACTIONS``.

        Args:
            model_name: Human-readable model label (e.g. ``"Qwen3.5-0.8B"``).
            variant_type: One of ``"standard"``, ``"number_swap"``,
                          ``"irrelevant_sentence"``.

        Returns:
            List of per-question result dicts with keys
            ``question_id``, ``correct``, ``response``, ``elapsed_s``.

        Raises:
            TimeoutError: Re-raised if ``generate_fn`` raises ``TimeoutError``
                          (caller should catch this and emit a partial artifact).
        """
        questions = self._build_variant_questions(variant_type)
        total = len(questions)

        ckpt_path = _ckpt_path(self.checkpoint_dir, model_name=model_name, variant_type=variant_type)
        ckpt = _load_ckpt(ckpt_path)
        completed: dict[str, Any] = dict(ckpt.get("completed", {}))

        results: list[dict[str, Any]] = []
        # Accumulated logits — list of (seq_len, vocab_size) per-question arrays.
        logit_buffer: list[np.ndarray] = []
        # Track which prefix fractions we have already saved to avoid duplicates.
        saved_fractions: set[int] = set()
        # Logit paths dict for this (model, variant) pair.
        variant_logit_paths: dict[str, str] = {}

        for idx, item in enumerate(questions):
            qid = item["question_id"]
            question = item["question"]
            expected = item["expected_answer"]

            if qid in completed:
                # Resume: reconstruct result from checkpoint without calling generate_fn.
                r = completed[qid]
                results.append(r)
                # We cannot recover logits from checkpoint; keep buffer as-is.
                continue

            t0 = time.perf_counter()
            response, logits = self.generate_fn(
                question,
                expected,
                model_name=model_name,
                variant_type=variant_type,
            )
            elapsed = time.perf_counter() - t0

            correct = _is_correct(response, expected)
            result = {
                "question_id": qid,
                "correct": correct,
                "response": response,
                "elapsed_s": round(elapsed, 3),
            }
            results.append(result)
            completed[qid] = result

            # Accumulate logits (strip batch dim: (1, seq_len, vocab) → (seq_len, vocab)).
            if logits.ndim == 3:
                logit_buffer.append(logits[0])
            else:
                logit_buffer.append(logits)

            # Checkpoint every CHECKPOINT_INTERVAL questions.
            n_done = idx + 1
            if n_done % CHECKPOINT_INTERVAL == 0 or n_done == total:
                _save_ckpt(ckpt_path, {
                    "model_name": model_name,
                    "variant_type": variant_type,
                    "completed": completed,
                })

            # Save logits at prefix fractions (REQ-VERIFY-067).
            if total > 0:
                progress = n_done / total
                for frac in LOGIT_FRACTIONS:
                    pct = int(round(frac * 100))
                    if pct not in saved_fractions and progress >= frac:
                        # Build (n, seq_len, vocab) object array from buffer.
                        arr = np.empty(len(logit_buffer), dtype=object)
                        for i, lg in enumerate(logit_buffer):
                            arr[i] = lg
                        out_path = _save_logits(
                            self.logit_dir,
                            model_name=model_name,
                            variant_type=variant_type,
                            pct=pct,
                            logit_list=logit_buffer,
                        )
                        variant_logit_paths[f"{pct}pct"] = out_path
                        saved_fractions.add(pct)

        # Store logit paths.
        self._logit_paths.setdefault(model_name, {}).update(variant_logit_paths)

        return results

    # ------------------------------------------------------------------
    # Per-model aggregation
    # ------------------------------------------------------------------

    def run_all_variants(self, *, model_name: str) -> dict[str, Any]:
        """Run all three variant types for one model and return accuracy stats.

        Args:
            model_name: Human-readable model label.

        Returns:
            Dict ``{variant_type: {"correct": int, "total": int, "accuracy": float}}``
            for the three variant types: ``"standard"``, ``"number_swap"``,
            ``"irrelevant_sentence"``.

        Raises:
            TimeoutError: Propagated from ``run_variant`` on inference timeout.
        """
        variant_stats: dict[str, Any] = {}
        for vt in ("standard", "number_swap", "irrelevant_sentence"):
            results = self.run_variant(model_name=model_name, variant_type=vt)
            n_correct = sum(1 for r in results if r.get("correct"))
            n_total = len(results)
            variant_stats[vt] = {
                "correct": n_correct,
                "total": n_total,
                "accuracy": n_correct / n_total if n_total else 0.0,
            }
        self._model_results[model_name] = variant_stats
        return variant_stats

    def run_all_models(self) -> dict[str, dict[str, Any]]:
        """Run all configured models across all variants.

        Iterates through ``self.model_specs`` and calls ``run_all_variants``
        for each.  In live mode the DualGPURunner routes each model to its
        assigned GPU; in mock mode inference calls are sequential.

        Returns:
            Dict ``{model_name: variant_stats}`` aggregated across all models.

        Raises:
            TimeoutError: Propagated from ``run_all_variants`` on inference timeout.
        """
        for spec in self.model_specs:
            self.run_all_variants(model_name=spec["name"])
        return dict(self._model_results)

    # ------------------------------------------------------------------
    # Timeout-aware top-level entry point
    # ------------------------------------------------------------------

    def run_with_timeout_handling(
        self,
        *,
        output_path: Path,
        run_date: str = RUN_DATE,
        inference_mode: str | None = None,
    ) -> dict[str, Any]:
        """Run all models/variants, writing a partial artifact on timeout.

        The 60 s per-call timeout is enforced by the ``generate_fn`` caller
        contract: if ``generate_fn`` raises ``TimeoutError``, this method
        catches it, builds a partial artifact with ``stall_at`` set to the
        current ``"model_name:variant_type:question_id"``, writes it to
        *output_path*, and returns it.

        For a clean run, a full artifact is written and returned instead.

        Args:
            output_path: Destination JSON path for the experiment artifact.
            run_date: Date string in ``YYYYMMDD`` format.
            inference_mode: Override for the ``inference_mode`` artifact field.
                            Defaults to ``"live_gpu"`` if ``CARNOT_FORCE_LIVE=1``,
                            otherwise ``"mock"``.

        Returns:
            The artifact dict (may be partial if a timeout occurred).
        """
        if inference_mode is None:
            inference_mode = (
                "live_gpu" if os.environ.get("CARNOT_FORCE_LIVE", "0") == "1" else "mock"
            )

        started_at = utc_now()
        stall_at: str | None = None

        try:
            for spec in self.model_specs:
                model_name = spec["name"]
                for vt in ("standard", "number_swap", "irrelevant_sentence"):
                    questions = self._build_variant_questions(vt)
                    for item in questions:
                        qid = item["question_id"]
                        question = item["question"]
                        expected = item["expected_answer"]

                        # Check checkpoint — skip if already done.
                        ckpt_path = _ckpt_path(
                            self.checkpoint_dir,
                            model_name=model_name,
                            variant_type=vt,
                        )
                        ckpt = _load_ckpt(ckpt_path)
                        if qid in ckpt.get("completed", {}):
                            continue

                        # Call generate_fn; TimeoutError propagates here.
                        _response, _logits = self.generate_fn(
                            question,
                            expected,
                            model_name=model_name,
                            variant_type=vt,
                        )
                        # If we reach here the call succeeded — update checkpoint.
                        ckpt.setdefault("completed", {})[qid] = {
                            "question_id": qid,
                            "correct": _is_correct(_response, expected),
                            "response": _response,
                        }
                        _save_ckpt(ckpt_path, ckpt)

        except TimeoutError:
            # Emit partial artifact with stall_at set to identify where we stalled.
            # stall_at format: "model_name:variant_type:question_id"
            stall_at = f"{model_name}:{vt}:{qid}"  # type: ignore[possibly-undefined]

        # Rebuild complete model_results from checkpoints.
        self._rebuild_results_from_checkpoints()

        finished_at = utc_now()
        artifact = build_artifact(
            run_date=run_date,
            started_at=started_at,
            finished_at=finished_at,
            inference_mode=inference_mode,
            model_results=self._model_results,
            logit_paths=self._logit_paths,
            stall_at=stall_at,
        )

        output_path.parent.mkdir(parents=True, exist_ok=True)
        tmp = output_path.with_suffix(".tmp")
        tmp.write_text(json.dumps(artifact, indent=2) + "\n", encoding="utf-8")
        tmp.replace(output_path)

        return artifact

    def _rebuild_results_from_checkpoints(self) -> None:
        """Recompute ``self._model_results`` from checkpoint files written so far.

        This is called after a complete or partial run to ensure the artifact
        reflects the latest checkpoint state rather than any partially-updated
        in-memory state.
        """
        for spec in self.model_specs:
            model_name = spec["name"]
            variant_stats: dict[str, Any] = {}
            for vt in ("standard", "number_swap", "irrelevant_sentence"):
                ckpt_path = _ckpt_path(
                    self.checkpoint_dir, model_name=model_name, variant_type=vt
                )
                ckpt = _load_ckpt(ckpt_path)
                completed = ckpt.get("completed", {})
                results = list(completed.values())
                n_correct = sum(1 for r in results if r.get("correct"))
                n_total = len(results)
                variant_stats[vt] = {
                    "correct": n_correct,
                    "total": n_total,
                    "accuracy": n_correct / n_total if n_total else 0.0,
                }
            self._model_results[model_name] = variant_stats


