"""Exp 431 — EORM + JEPA Retrain on FOVER-Labeled Real Pairs (RETRO-024 Closure Attempt).

**Researcher summary:**
    RETRO-024 has been open for 6 consecutive milestones because all EORM/JEPA retrains
    used synthetic-only data.  Exp 430 produced the missing training data: real (step_text,
    label) pairs generated by running live LLM CoT responses through the FOVERAnnotator
    Z3 pipeline.

    This experiment:
    1. Loads FOVER-labeled pairs from results/fover_labeled_steps.json.
    2. Falls back to synthetic corpus if < 10 real pairs are available.
    3. Evaluates EORM before_auc on a held-out 20% test split.
    4. Retrains EORM for 100 epochs on FOVER contrastive (correct, incorrect) triples,
       checkpointing every 25 epochs.
    5. Evaluates EORM after_auc on the same held-out set.
    6. Retrains JEPA predictor on the same pairs mapped to (step_prefix, violation_flag).
    7. Saves eorm_431_real.safetensors and jepa_431_real.safetensors.
    8. Emits schema='carnot.eorm_jepa_retrain.v2' artifact with honest_verdict.
    9. Sets retro_024_closed=True if honest_verdict='real_data_improvement'.

**Honest reporting:**
    - 'real_data_improvement': >= 10 real pairs AND after_auc > before_auc.
      RETRO-024 is closed.
    - 'synthetic_only': < 10 real pairs — live FOVER annotation required first.
    - 'real_data_no_improvement': >= 10 real pairs but AUC did not improve.
      RETRO-024 remains open; investigate learning rate or epoch count.

**Usage:**
    JAX_PLATFORMS=cpu python scripts/experiment_431_eorm_jepa_real_retrain.py
    CARNOT_FORCE_LIVE=1 python scripts/experiment_431_eorm_jepa_real_retrain.py

Spec: REQ-LEARN-032, REQ-LEARN-033,
      SCENARIO-LEARN-057, SCENARIO-LEARN-058, SCENARIO-LEARN-059
"""

