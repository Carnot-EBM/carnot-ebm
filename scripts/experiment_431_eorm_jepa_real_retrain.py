# ---------------------------------------------------------------------------
# AUC-ROC evaluator for EORM (same implementation as Exp 359)
# ---------------------------------------------------------------------------


def _evaluate_eorm_auc(model: EORMModel, pairs: list[ViolationPair]) -> float:
    """Compute AUC-ROC for EORM model on a ViolationPair test set.

    EORM outputs lower energy for responses it considers more correct.
    High energy predicts violation, so we use -energy as the discrimination score
    (consistent with JEPARetrainer.evaluate_auc_roc and Exp 359).

    Args:
        model: Trained EORMModel.
        pairs: ViolationPair test examples.

    Returns:
        AUC-ROC in [0, 1]. 0.5 = random baseline.
    """
    if not pairs:
        return 0.5

    scores: list[float] = []
    labels: list[int] = []

    for p in pairs:
        cot = CoTEnergyInput(
            question_text=p.question_id,
            response_text=p.full_response,
        )
        energy = model.energy(cot)
        scores.append(-energy)  # high negated energy = predicted violation
        labels.append(1 if p.has_violation else 0)

    n_pos = sum(labels)
    n_neg = len(labels) - n_pos
    if n_pos == 0 or n_neg == 0:
        return 0.5

    scored = sorted(zip(scores, labels), key=lambda x: x[0], reverse=True)

    tpr_pts = [0.0]
    fpr_pts = [0.0]
    tp = fp = 0

    for _s, lab in scored:
        if lab == 1:
            tp += 1
        else:
            fp += 1
        tpr_pts.append(tp / n_pos)
        fpr_pts.append(fp / n_neg)

    auc = 0.0
    for i in range(1, len(fpr_pts)):
        dfpr = fpr_pts[i] - fpr_pts[i - 1]
        auc += dfpr * (tpr_pts[i] + tpr_pts[i - 1]) / 2.0

    return float(auc)


# ---------------------------------------------------------------------------
# Convert FOVER pairs to ViolationPairs for JEPA training
# ---------------------------------------------------------------------------


def _fover_pairs_to_violation_pairs(fover_pairs: list[dict]) -> list[ViolationPair]:
    """Map FOVER labeled steps to ViolationPair objects for JEPARetrainer.

    Each FOVER step is mapped as:
    - label='incorrect' -> has_violation=True
    - label='correct'   -> has_violation=False

    The full step_text is used as both partial_response and full_response because
    CoT steps are already short (JEPA training does not need a prefix split here —
    we are training the violation detector on the full step text, not a prefix).

    Args:
        fover_pairs: FOVER pair dicts (from load_fover_pairs).

    Returns:
        List of ViolationPair objects for JEPARetrainer.train_epoch.
    """
    result: list[ViolationPair] = []
    for p in fover_pairs:
        result.append(
            ViolationPair(
                partial_response=p["step_text"],
                full_response=p["step_text"],
                has_violation=(p["label"] == "incorrect"),
                model_id="fover_labeled",
                question_id=p["question_id"],
            )
        )
    return result


# ---------------------------------------------------------------------------
# Save JEPA model parameters as safetensors
# ---------------------------------------------------------------------------


def _save_jepa_model(model: ContextPredictionEnergy, path: str) -> None:
    """Save ContextPredictionEnergy parameters as a safetensors file.

    ContextPredictionEnergy shares the same parameter layout as GibbsModel:
    - layers: list of (weight, bias) JAX arrays
    - output_weight: 1-D JAX array
    - output_bias: float

    We flatten this to a dict of numpy arrays keyed as 'layer_N_weight',
    'layer_N_bias', 'output_weight', 'output_bias' for safetensors compatibility.

    Args:
        model: ContextPredictionEnergy instance to save.
        path: Destination file path (should end in .safetensors).
    """
    from safetensors.numpy import save_file  # optional dep, imported locally

    np_flat: dict[str, np.ndarray] = {}
    for i, (w, b) in enumerate(model.layers):
        np_flat[f"layer_{i}_weight"] = np.array(w)
        np_flat[f"layer_{i}_bias"] = np.array(b)
    np_flat["output_weight"] = np.array(model.output_weight)
    np_flat["output_bias"] = np.array([model.output_bias], dtype=np.float32)

    Path(path).parent.mkdir(parents=True, exist_ok=True)
    save_file(np_flat, path)


# ---------------------------------------------------------------------------
# Load or build baseline EORM model
# ---------------------------------------------------------------------------


def _load_or_build_eorm_model(root: Path) -> EORMModel:
    """Load the Exp 359 EORM model, or fall back to Exp 346, or build fresh.

    Preference order (most recent trained model first):
    1. results/eorm_model_359_real.safetensors  (Exp 359 retrain)
    2. results/eorm_model_346.safetensors       (Exp 346 synthetic baseline)
    3. Fresh random init with seed 431

    This ensures that before_auc reflects whatever level of training has been
    done so far, rather than always starting from random initialization.
    """
    for candidate in [
        root / "results" / "eorm_model_359_real.safetensors",
        root / "results" / "eorm_model_346.safetensors",
    ]:
        if candidate.exists():
            try:
                model = EORMModel.load(str(candidate))
                _log.info("Loaded EORM baseline from %s", candidate)
                return model
            except Exception as exc:
                _log.warning("Could not load %s (%s); trying next", candidate, exc)

    model = EORMModel(
        embed_dim=EMBED_DIM,
        n_heads=N_HEADS,
        n_layers=N_LAYERS,
        key=jrandom.PRNGKey(431),
    )
    _log.info("Built fresh EORMModel (embed_dim=%d, n_layers=%d)", EMBED_DIM, N_LAYERS)
    return model


# ---------------------------------------------------------------------------
# Build EORM contrastive triples from FOVER pair embeddings
# ---------------------------------------------------------------------------


def _build_eorm_triples(
    fover_pairs: list[dict],
    violation_pairs: list[ViolationPair],
) -> list[tuple[str, str, str]]:
    """Build (correct_response, incorrect_response, question_id) triples for EORMTrainer.

    Groups ViolationPairs by question_id and cross-matches correct vs incorrect responses,
    consistent with _pairs_to_contrastive_triples in Exp 359.

    Args:
        fover_pairs: FOVER pair dicts (for question_id grouping).
        violation_pairs: Parallel ViolationPair list (for response text and label).

    Returns:
        List of (correct_response, incorrect_response, question_text) triples.
    """
    from collections import defaultdict

    correct_by_q: dict[str, list[str]] = defaultdict(list)
    incorrect_by_q: dict[str, list[str]] = defaultdict(list)
    _SHARED_POOL = "_synthetic_pool"

    for vp in violation_pairs:
        q_id = vp.question_id
        if q_id == "unknown" or q_id.startswith("synthetic_"):
            key = _SHARED_POOL
        else:
            key = q_id
        if vp.has_violation:
            incorrect_by_q[key].append(vp.full_response)
        else:
            correct_by_q[key].append(vp.full_response)

    all_keys = set(correct_by_q.keys()) | set(incorrect_by_q.keys())
    triples: list[tuple[str, str, str]] = []

    for key in sorted(all_keys):
        corrects = correct_by_q.get(key, [])
        incorrects = incorrect_by_q.get(key, [])
        if not corrects or not incorrects:
            continue
        n = max(len(corrects), len(incorrects))
        for i in range(n):
            c = corrects[i % len(corrects)]
            ic = incorrects[i % len(incorrects)]
            triples.append((c, ic, key))

    return triples


# ---------------------------------------------------------------------------
# Main experiment logic
# ---------------------------------------------------------------------------


def run_experiment(
    *,
    force_live: bool = False,
    repo_root: Path | None = None,
) -> dict:
    """Execute Exp 431: EORM + JEPA retrain on FOVER real pairs.

    All file paths can be overridden via repo_root for test isolation.

    Args:
        force_live: If True, behave as if CARNOT_FORCE_LIVE=1 (informational; the
                    experiment runs identically in CI and live since EORM is CPU-only).
        repo_root: Override repo root (used in tests to isolate file I/O).

    Returns:
        Full experiment artifact dict (also written to DELIVERABLE JSON).
    """
    _root = repo_root or _REPO_ROOT

    # Step 1: apply_env_autofix FIRST (RETRO-022 belt-and-suspenders)
    autofix = apply_env_autofix()
    _log.info("env_autofix: gpu_detected=%s auto_fix_applied=%s", autofix.gpu_detected, autofix.auto_fix_applied)

    tmpl = ExperimentTemplate(
        EXPERIMENT_ID,
        TITLE,
        DELIVERABLE,
        requires_gpu=False,  # EORM/JEPA retrain is CPU-only (JAX_PLATFORMS=cpu)
        repo_root=_root,
    )
    tmpl.setup()

    # Step 2: Load FOVER labeled pairs
    fover_path = str(_root / "results" / "fover_labeled_steps.json")
    fover_pairs = load_fover_pairs(fover_path)
    n_real = len(fover_pairs)
    _log.info("Loaded %d FOVER real pairs from %s", n_real, fover_path)

    # Step 3: Determine retrain mode and build corpus
    if n_real >= REAL_PAIR_THRESHOLD:
        retrain_mode = "real_data"
        violation_pairs = _fover_pairs_to_violation_pairs(fover_pairs)
        _log.info("Using %d real FOVER pairs for EORM and JEPA retrain", n_real)
    else:
        retrain_mode = "synthetic_only"
        _log.info(
            "Only %d real pairs (threshold %d); falling back to synthetic corpus",
            n_real, REAL_PAIR_THRESHOLD,
        )
        synthetic_eorm = make_synthetic_eorm_pairs(n=SYNTHETIC_EORM_N, seed=431)
        synthetic_jepa = _make_synthetic_pairs(n=SYNTHETIC_JEPA_N, seed=431)
        violation_pairs = list(synthetic_eorm) + list(synthetic_jepa)
        # Replace fover_pairs with synthetic equivalents for contrastive builder
        fover_pairs = [
            {
                "question_id": vp.question_id,
                "step_text": vp.full_response,
                "label": "incorrect" if vp.has_violation else "correct",
                "confidence": 1.0,
            }
            for vp in violation_pairs
        ]

    # Train / test split (80/20, no shuffle for reproducibility)
    n_train = max(1, int(len(violation_pairs) * TRAIN_SPLIT))
    train_vp = violation_pairs[:n_train]
    test_vp = violation_pairs[n_train:] if len(violation_pairs) > n_train else violation_pairs

    train_fover = fover_pairs[:n_train]

    # Step 4: Load / build EORM baseline and evaluate before_auc
    eorm_model = _load_or_build_eorm_model(_root)
    before_auc = _evaluate_eorm_auc(eorm_model, test_vp)
    _log.info("EORM before_auc = %.4f", before_auc)

    # Step 5: Build contrastive triples and retrain EORM (100 epochs, checkpoint every 25)
    triples = _build_eorm_triples(train_fover, train_vp)
    _log.info(
        "Training EORM for %d epochs on %d contrastive triples",
        N_EPOCHS, len(triples),
    )

    eorm_trainer = EORMTrainer(eorm_model, lr=LR, margin=MARGIN)
    epoch_losses: list[float] = []

    if triples:
        for epoch in range(N_EPOCHS):
            loss = eorm_trainer.train_epoch(triples, batch_size=BATCH_SIZE)
            epoch_losses.append(loss)

            if (epoch + 1) % CHECKPOINT_EVERY == 0:
                _log.info("Epoch %d/%d — mean loss = %.4f", epoch + 1, N_EPOCHS, loss)
                checkpoint_data = {
                    "epoch": epoch + 1,
                    "loss": round(loss, 6),
                    "n_triples": len(triples),
                }
                tmpl.checkpoint_save(checkpoint_data, step=epoch + 1)
    else:
        _log.warning(
            "No contrastive triples formed (need correct+incorrect pairs per question). "
            "EORM parameters unchanged."
        )

    # Step 6: Evaluate after_auc
    after_auc = _evaluate_eorm_auc(eorm_model, test_vp)
    _log.info("EORM after_auc = %.4f (improvement = %+.4f)", after_auc, after_auc - before_auc)

    # Step 7: Retrain JEPA on FOVER violation pairs
    jepa_config = JEPAEnergyConfig(embed_dim=JEPA_EMBED_DIM, hidden_dims=JEPA_HIDDEN_DIMS)
    jepa_model = ContextPredictionEnergy(config=jepa_config, key=jrandom.PRNGKey(431))
    jepa_retrainer = JEPARetrainer(jepa_model, lr=LR)

    jepa_before_auc = jepa_retrainer.evaluate_auc_roc(test_vp)
    _log.info("JEPA before_auc = %.4f", jepa_before_auc)

    if train_vp:
        jepa_train_epochs = max(10, N_EPOCHS // 5)
        for epoch in range(jepa_train_epochs):
            jepa_retrainer.train_epoch(train_vp, batch_size=BATCH_SIZE)

    jepa_after_auc = jepa_retrainer.evaluate_auc_roc(test_vp)
    _log.info("JEPA after_auc = %.4f (improvement = %+.4f)", jepa_after_auc, jepa_after_auc - jepa_before_auc)

    # Step 8: Save models
    eorm_path = str(_root / "results" / "eorm_431_real.safetensors")
    jepa_path = str(_root / "results" / "jepa_431_real.safetensors")

    try:
        eorm_model.save(eorm_path)
        _log.info("Saved EORM model to %s", eorm_path)
    except Exception as exc:
        _log.warning("Could not save EORM model: %s", exc)
        eorm_path = ""

    try:
        _save_jepa_model(jepa_model, jepa_path)
        _log.info("Saved JEPA model to %s", jepa_path)
    except Exception as exc:
        _log.warning("Could not save JEPA model: %s", exc)
        jepa_path = ""

    # Step 9: Compute honest verdict and build artifact
    honest_verdict = compute_retrain_verdict(before_auc, after_auc, n_real)
    retro_024_closed = honest_verdict == "real_data_improvement"

    _log.info(
        "honest_verdict=%s retro_024_closed=%s",
        honest_verdict, retro_024_closed,
    )

    artifact = tmpl.build_result(
        {
            "schema": "carnot.eorm_jepa_retrain.v2",
            "retrain_mode": retrain_mode,
            "n_real_pairs": n_real,
            "before_auc": round(before_auc, 6),
            "after_auc": round(after_auc, 6),
            "auc_improvement": round(after_auc - before_auc, 6),
            "honest_verdict": honest_verdict,
            "retro_024_closed": retro_024_closed,
            "eorm_model_path": eorm_path,
            "jepa_before_auc": round(jepa_before_auc, 6),
            "jepa_after_auc": round(jepa_after_auc, 6),
            "jepa_model_path": jepa_path,
            "n_contrastive_triples": len(triples),
            "n_train_pairs": len(train_vp),
            "n_test_pairs": len(test_vp),
            "n_eorm_epochs": N_EPOCHS,
        },
        status="success",
    )

    return artifact


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def main() -> None:
    """Run Exp 431 with watchdog, write results to deliverable JSON."""
    force_live = bool(int(os.environ.get("CARNOT_FORCE_LIVE", "0")))

    watchdog = ExperimentTimeoutWatchdog(
        EXPERIMENT_ID,
        timeout_minutes=45,
        result_path=str(_REPO_ROOT / DELIVERABLE),
    )

    with watchdog:
        artifact = run_experiment(force_live=force_live)

    deliverable = _REPO_ROOT / DELIVERABLE
    deliverable.parent.mkdir(parents=True, exist_ok=True)
    with open(deliverable, "w") as f:
        json.dump(artifact, f, indent=2)

    _log.info(
        "Exp 431 complete. honest_verdict=%s retro_024_closed=%s -> %s",
        artifact.get("honest_verdict"),
        artifact.get("retro_024_closed"),
        deliverable,
    )


if __name__ == "__main__":
    main()
