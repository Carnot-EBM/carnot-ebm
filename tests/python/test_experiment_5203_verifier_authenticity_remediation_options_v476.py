def test_req_verify_5203_validate_artifact_rejects_schema_drift(tmp_path: Path) -> None:
    """REQ-VERIFY-5203: artifact validation rejects missing fields and dishonest wrappers."""

    root = make_repo(tmp_path)
    valid = mod.build_artifact(root=root, result_path=root / mod.RESULT_RELATIVE_PATH)

    def clone() -> dict[str, object]:
        return json.loads(json.dumps(valid))

    def expect_error(
        payload: dict[str, object], message: str, *, fix_checksum: bool = True
    ) -> None:
        if fix_checksum:
            payload["reproducibility_checksum"] = mod.payload_checksum(payload)
        with pytest.raises(AssertionError, match=message):
            mod.validate_artifact(payload)

    broken = clone()
    del broken["schema"]
    expect_error(broken, "missing required fields", fix_checksum=False)

    broken = clone()
    broken["schema"] = "wrong"
    expect_error(broken, "schema mismatch")

    broken = clone()
    broken["experiment_id"] = "wrong"
    expect_error(broken, "experiment_id mismatch")

    broken = clone()
    broken["and_composition_verifier_options"] = {}
    expect_error(broken, "must be principle-wrapped")

    broken = clone()
    broken["and_composition_verifier_options"]["principle"] = "wrong"
    expect_error(broken, "principle mismatch")

    broken = clone()
    del broken["and_composition_verifier_options"]["value"]["rename"]
    expect_error(broken, "missing option keys")

    broken = clone()
    broken["and_composition_verifier_options"]["value"]["recommendation"] = ""
    expect_error(broken, "non-empty strings")

    broken = clone()
    broken["audit_findings_independently_reconfirmed"]["value"] = "true"
    expect_error(broken, "must be bool")

    broken = clone()
    broken["no_verifier_modified_this_task"]["value"] = False
    expect_error(broken, "verifier source modification")

    broken = clone()
    broken["inference_substrate"]["value"] = "live_model_inference"
    expect_error(broken, "inference_substrate mismatch")

    broken = clone()
    broken["honest_verdict"]["value"] = "blocked_without_terminal_prefix"
    expect_error(broken, "must start")

    broken = clone()
    broken["reproducibility_checksum"] = "bad"
    expect_error(broken, "checksum mismatch", fix_checksum=False)


