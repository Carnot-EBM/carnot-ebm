"""Tests for Experiment 1037 — KV260 First Light v6.

These tests verify the schema and offline logic of the experiment driver.
The driver itself talks to a physical KV260 board over SSH, so tests do
not run the full experiment — they only exercise pure-Python pieces
(``_write_guide``, the artifact schema) and validate the produced JSON
once it has been generated by a live run.

Spec refs: REQ-HW-040, SCENARIO-HW-040
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from scripts import experiment_1037_kv260_v6 as exp1037
from scripts import kv260_ising_smoke_test as smoke


_REPO_ROOT = Path(__file__).parent.parent.parent
_ARTIFACT = _REPO_ROOT / "results" / "experiment_1037_kv260_v6.json"


def test_guide_for_all_paths_blocked_includes_serial_recovery():
    """If SSH never came up, the guide must direct the operator to the
    serial-console / SD-card recovery path rather than the bitstream
    refresh path."""
    cmds = exp1037._write_guide("all_paths_blocked", None, "")
    assert len(cmds) == 5
    blob = "\n".join(cmds)
    assert "lsblk" in blob  # SD card identification
    assert "minicom" in blob or "ttyUSB" in blob  # serial console step


def test_guide_for_ssh_ok_includes_bootgen_step():
    """If SSH worked but bitstream load failed, the guide must tell the
    operator to regenerate the .bit.bin via bootgen — that is the
    most common cause of ``xmutil loadapp`` returning Load Error: -1."""
    cmds = exp1037._write_guide("guide_written", "ubuntu", "Load Error: -1")
    assert len(cmds) == 5
    blob = "\n".join(cmds)
    assert "bootgen" in blob
    assert "192.168.51.98" in blob
    assert "ubuntu@" in blob


def test_guide_for_first_light_includes_smoke_followup():
    """Even on full success the guide is non-empty so the operator can
    re-verify after a reboot or re-flash."""
    cmds = exp1037._write_guide("first_light_achieved", "ubuntu", "")
    assert len(cmds) == 5
    assert any("xmutil" in c for c in cmds)


def test_smoke_test_handles_bad_json():
    """``run_smoke_test`` must report a clean error structure if the
    on-board program prints garbage instead of JSON.  We simulate that
    by patching subprocess.run to return a known stdout."""
    import subprocess
    import unittest.mock as mock

    fake = mock.Mock()
    fake.returncode = 0
    fake.stdout = "this is not json"
    fake.stderr = ""
    with mock.patch.object(subprocess, "run", return_value=fake):
        result = smoke.run_smoke_test("203.0.113.1", "ubuntu")
    assert result["ok"] is False
    assert result["passed"] is False
    assert "no_json_in_output" in result["error"]


def test_smoke_test_handles_ssh_timeout():
    """SSH timeouts must surface as a structured error rather than an
    exception — the experiment driver relies on this to write the
    artifact even when the board is unresponsive."""
    import subprocess
    import unittest.mock as mock

    def _raise(*_a, **_kw):
        raise subprocess.TimeoutExpired(cmd="ssh", timeout=1)

    with mock.patch.object(subprocess, "run", side_effect=_raise):
        result = smoke.run_smoke_test("203.0.113.1", "ubuntu")
    assert result["ok"] is False
    assert result["error"] == "ssh_timeout"


def test_smoke_test_passes_on_nonuniform_distribution():
    """Happy path: on-board program returns a non-uniform energy
    distribution and ``passed`` is True."""
    import subprocess
    import unittest.mock as mock

    fake_stdout = json.dumps(
        {
            "samples": 100,
            "unique_values": 17,
            "min_value": 0,
            "max_value": 0xFFFFFFFF,
            "min_popcount": 12,
            "max_popcount": 32,
            "mean_popcount": 24.5,
            "energy_range": 20,
            "first_5_hex": ["0xff00ffff"],
        }
    )
    fake = mock.Mock(returncode=0, stdout=fake_stdout, stderr="")
    with mock.patch.object(subprocess, "run", return_value=fake):
        result = smoke.run_smoke_test("203.0.113.1", "ubuntu")
    assert result["passed"] is True
    assert result["energy_distribution_nonuniform"] is True


def test_smoke_test_fails_on_uniform_distribution():
    """If the FPGA isn't actually computing, every readout returns the
    same constant — energy_range = 0 — and the test must fail rather
    than silently pass."""
    import subprocess
    import unittest.mock as mock

    fake_stdout = json.dumps(
        {
            "samples": 100,
            "unique_values": 1,
            "min_value": 0xDEADBEEF,
            "max_value": 0xDEADBEEF,
            "min_popcount": 24,
            "max_popcount": 24,
            "mean_popcount": 24.0,
            "energy_range": 0,
            "first_5_hex": ["0xdeadbeef"] * 5,
        }
    )
    fake = mock.Mock(returncode=0, stdout=fake_stdout, stderr="")
    with mock.patch.object(subprocess, "run", return_value=fake):
        result = smoke.run_smoke_test("203.0.113.1", "ubuntu")
    assert result["passed"] is False


@pytest.mark.skipif(not _ARTIFACT.exists(), reason="experiment_1037 artifact not yet produced")
def test_artifact_schema():
    """The produced artifact must contain every field the .80 milestone
    task spec demands.  This test only runs when the experiment has
    been executed — it doesn't trigger a live SSH attempt itself."""
    data = json.loads(_ARTIFACT.read_text())
    required_fields = {
        "experiment",
        "title",
        "run_date",
        "schema",
        "duration_s",
        "ssh_reachable",
        "ssh_approach_used",
        "bitstream_loaded",
        "smoke_test_passed",
        "energy_distribution_nonuniform",
        "kv260_guide_written",
        "guide_commands",
        "honest_verdict",
    }
    missing = required_fields - data.keys()
    assert not missing, f"missing required fields: {missing}"
    assert data["experiment"] == 1037
    assert data["honest_verdict"] in {
        "first_light_achieved",
        "ssh_restored_bitstream_loaded",
        "guide_written",
        "all_paths_blocked",
    }
    assert isinstance(data["guide_commands"], list)
    if data["kv260_guide_written"]:
        assert len(data["guide_commands"]) == 5
