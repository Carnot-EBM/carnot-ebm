# compute_retrain_verdict
# ---------------------------------------------------------------------------


def compute_retrain_verdict(
    before_auc: float,
    after_auc: float,
    n_real_pairs: int,
) -> str:
    """Determine the honest verdict for an EORM/JEPA retrain experiment.

    **Detailed explanation for engineers:**
        The verdict string is the key field that determines whether RETRO-024 is
        closed.  Three mutually exclusive outcomes:

        'real_data_improvement':
            after_auc > before_auc AND n_real_pairs >= 10.
            This is the only outcome that constitutes genuine evidence of real-world
            improvement.  AUC > 0.5 on real pairs means the model has learned
            something beyond random chance from real LLM-generated data.

        'synthetic_only':
            n_real_pairs < 10 regardless of AUC values.
            Fewer than 10 real pairs is insufficient for a meaningful retrain.
            We fall back to synthetic data; the AUC may improve but that improvement
            reflects synthetic corpus quality, not real-world performance.
            The threshold of 10 is intentionally conservative: 10 pairs gives at most
            5 contrastive triples (5 correct + 5 incorrect per question, best case),
            which is barely enough for one gradient step.

        'real_data_no_improvement':
            n_real_pairs >= 10 AND after_auc <= before_auc.
            Real data was available but the retrain did not improve AUC.  This honest
            negative result is logged for future analysis (more data? lower LR? more
            epochs?).  It does NOT close RETRO-024 — the problem remains open.

    Args:
        before_auc: AUC-ROC on held-out test set before retraining.
        after_auc: AUC-ROC on held-out test set after retraining.
        n_real_pairs: Number of real FOVER-labeled pairs used for training.

    Returns:
        One of: 'real_data_improvement', 'synthetic_only', 'real_data_no_improvement'.

    Spec: REQ-LEARN-032, SCENARIO-LEARN-059
    """
    if n_real_pairs < 10:
        return "synthetic_only"
    if after_auc > before_auc:
        return "real_data_improvement"
    return "real_data_no_improvement"
