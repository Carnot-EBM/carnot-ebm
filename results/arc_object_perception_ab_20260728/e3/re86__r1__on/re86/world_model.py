def engine(grid, action, data):
    if action == 4:
        if data is None:
            return grid
        px, py = data['x'], data['y']
        logical_x, logical_y = px // 1, py // 1
        if logical_x >= grid.shape[1] or logical_y >= grid.shape[0]:
            return grid
        grid_copy = grid.copy()
        grid_copy[logical_y, logical_x] = 9
        return grid_copy
    elif action == 5:
        if data is None:
            return grid
        px, py = data['x'], data['y']
        logical_x, logical_y = px // 1, py // 1
        if logical_x >= grid.shape[1] or logical_y >= grid.shape[0]:
            return grid
        grid_copy = grid.copy()
        grid_copy[logical_y, logical_x] = 0
        return grid_copy
    elif action == 1:
        if data is None:
            return grid
        grid_copy = grid.copy()
        grid_copy[10:, 21] = 11
        grid_copy[24, 10] = 11
        grid_copy[27, 10] = 5
        grid_copy[36, 21] = 5
        grid_copy[37, 21] = 5
        grid_copy[38, 21] = 5
        return grid_copy
    return grid

