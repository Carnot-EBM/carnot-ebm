def is_level_complete(grid):
    import numpy as np
    if grid is None:
        return False
    grid = np.asarray(grid)
    if grid.shape[0] < 2 or grid.shape[1] < 2:
        return False
    # Check if the grid is fully filled with non-empty cells
    if np.all(grid != 0):
        return True
    return False
