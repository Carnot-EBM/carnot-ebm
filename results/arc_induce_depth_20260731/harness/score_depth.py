#!/usr/bin/env python3
"""Score the depth sweep: does raising max_depth fill the empty intersection?

READING ORDER, fixed so the null is as legible as the win:
  1. CONTROL FIDELITY -- depth 40 must reproduce the best-of-N result, or nothing below counts.
  2. THE INTERSECTION at each depth -- the pre-registered question.
  3. CONVERSIONS, itemised, with the termination reason that licenses calling each one a DEPTH
     effect rather than a budget effect.
  4. COST -- engine calls and wall time, so "raise the cap" carries its price.

WHY A CONVERSION REQUIRES `depth_capped` AT THE SHIPPED DEPTH. A candidate that terminated
`budget_exhausted` at depth 40 was not stopped by the cap, so if it becomes satisfiable at depth
200 the cause is ambiguous (more depth also means a different node ordering). Those are reported
separately as `converted_but_not_depth_attributable` and are NOT counted in the headline.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
from collections import Counter

OUT_DIR = pathlib.Path(__file__).resolve().parent.parent
REPO = OUT_DIR.parent.parent
BON = REPO / "results" / "arc_induce_bestofn_20260731"

raw = json.loads((OUT_DIR / "depth_sweep_raw.json").read_text())
bon = json.loads((BON / "bestofn_scored.json").read_text())

by_key = {
    f"{c['game']}|{c['candidate']}": c
    for c in bon["candidates"]
    if c.get("score_status") != "generation_failed"
}
stall = set(bon["stall_games"])
depths = raw["depths"]

# results[key][depth] = row
res: dict[str, dict[int, dict]] = {}
for r in raw["results"]:
    res.setdefault(r["_key"], {})[r["_depth"]] = r

SHIPPED = 40


def crit_i(key: str) -> bool:
    """Criterion (i) is joined in from best-of-N -- it contains no search and cannot vary with
    depth, so re-deriving it here would only create a way for the two artifacts to disagree."""
    return bool((by_key[key].get("criteria") or {}).get("i_dynamics"))


def crit_i_strict(key: str) -> bool:
    return bool((by_key[key].get("criteria") or {}).get("i_dynamics_strict"))


report: dict = {
    "schema": "carnot.arc_induce_depth_sweep.v1",
    "experiment": "arc_induce_depth_sweep_20260731",
    "question": (
        "Is the best-of-N empty intersection between criterion (i) (held-out dynamics) and "
        "criterion (iii) (a found plan) an artifact of max_depth=40, or is selecting on "
        "dynamics genuinely anti-selective for plannability?"
    ),
    "depths": depths,
    "shipped_depth": SHIPPED,
    # -- methodology (CLAUDE.md "Adversarial Artifact Verification + Sample-Size Rigor") --------
    "run_date": raw.get("run_date"),
    # The SWEEP's wall time (240 subprocess searches), not this scorer's -- the scorer executes
    # no generated code and its own runtime says nothing about whether the searches really ran.
    "duration_s": raw.get("wall_s"),
    "duration_s_note": (
        "Wall time of the 240-job sweep (48 candidates x 5 depths), each a separate killable "
        "subprocess. This is deliberately NOT LLM inference time: no model is loaded, so the "
        "60s live-inference floor does not apply -- see inference_substrate."
    ),
    "random_seed": 0,
    "random_seed_note": (
        "There is no sampling in this run and therefore nothing for a seed to control. The 48 "
        "completions were generated by the upstream best-of-N run and are FROZEN on disk; this "
        "sweep re-reads them and re-executes two deterministic searches per (candidate, depth). "
        "Recorded as 0 rather than omitted so the field is not mistaken for an oversight."
    ),
    "inference_substrate": "offline_arcade_live_agent_runtime_self_discovery_no_llm",
    "inference_substrate_note": (
        "No model is loaded and no GPU is touched: this executes induced Python engines inside "
        "the shipped goal gate and planner. GGUF names reachable from the upstream best-of-N "
        "artifact describe the generator that produced the completions, not anything invoked "
        "here."
    ),
    "verifier_is_oracle": True,
    "verifier_is_oracle_note": (
        "Declared True: no verifier-value or moat claim is made. Whether a plan exists at a "
        "given depth is decided by EXECUTING the induced engine, so the check IS the executable "
        "oracle. The finding is about a search bound, not about a verifier adding value."
    ),
    "cited_upstream_artifacts": [
        {
            "experiment_id": "arc_induce_bestofn_20260731",
            "fields_imported": [
                "candidates[].criteria.i_dynamics",
                "candidates[].criteria.i_dynamics_strict",
                "candidates[].shipped_gate_passes",
                "candidates[].goal_kind",
                "candidates[].plan_found",
                "stall_games",
                "postbank_games",
            ],
        }
    ],
    "preconditions_checked": [
        {"resource": "bestofn_scored.json", "available": (BON / "bestofn_scored.json").exists()},
        {"resource": "frozen_completions_bon_dir", "available": (BON / "harness" / "bon").is_dir()},
        {"resource": "root_grid_captures", "available": (BON / "harness" / "capture").is_dir()},
    ],
}

# ---- 1. control fidelity ---------------------------------------------------------------
mismatch = []
for key, per in res.items():
    row = per.get(SHIPPED)
    b = by_key.get(key)
    if not row or not b:
        continue
    for field in ("goal_satisfiable", "goal_kind", "plan_found"):
        if field in row and field in b and row[field] != b[field]:
            mismatch.append({"key": key, "field": field, "sweep": row[field], "bestofn": b[field]})
report["control_fidelity"] = {
    "compared": len([k for k in res if k in by_key]),
    "mismatches": mismatch,
    "note": (
        "ft09|5 is the KNOWN and explained difference: best-of-N recorded `gate_timeout` because "
        "it scores criterion (i) first and that engine does not terminate under "
        "WorldModelVerifier; this sweep skips criterion (i) (depth-invariant, joined in) and so "
        "reaches the gate, which returns immediately because the completion defines no "
        "is_level_complete. Any OTHER mismatch invalidates the sweep."
    ),
}

# ---- 2. the intersection, per depth ----------------------------------------------------
per_depth: dict[str, dict] = {}
for d in depths:
    i_set, iii_set, both = set(), set(), set()
    for key, per in res.items():
        if key not in by_key or by_key[key]["game"] not in stall:
            continue
        row = per.get(d) or {}
        if row.get("status") != "ok":
            continue
        if crit_i(key):
            i_set.add(key)
        if row.get("plan_found"):
            iii_set.add(key)
        if crit_i(key) and row.get("plan_found"):
            both.add(key)
    per_depth[str(d)] = {
        "n_criterion_i": len(i_set),
        "n_plan_found": len(iii_set),
        "n_INTERSECTION": len(both),
        "intersection_members": sorted(both),
        "plan_found_members": sorted(iii_set),
    }
report["stall_path_per_depth"] = per_depth

# ---- 3. conversions, attributed -------------------------------------------------------
conversions, non_attributable = [], []
for key, per in res.items():
    if key not in by_key or by_key[key]["game"] not in stall:
        continue
    base = per.get(SHIPPED) or {}
    if base.get("status") != "ok" or base.get("plan_found"):
        continue
    base_term = str(base.get("plan_diagnostics", {}).get("termination_reason") or "")
    for d in depths:
        if d <= SHIPPED:
            continue
        row = per.get(d) or {}
        if row.get("status") != "ok" or not row.get("plan_found"):
            continue
        rec = {
            "key": key,
            "game": by_key[key]["game"],
            "candidate": by_key[key]["candidate"],
            "criterion_i": crit_i(key),
            "criterion_i_strict": crit_i_strict(key),
            "shipped_gate_passes": by_key[key].get("shipped_gate_passes"),
            "heldout_accuracy": by_key[key].get("heldout_accuracy"),
            "first_depth_that_plans": d,
            "plan_length": row.get("plan_length"),
            "nodes_expanded": row.get("plan_diagnostics", {}).get("nodes_expanded"),
            "plan_wall_s": row.get("plan_wall_s"),
            "goal_kind_at_shipped_depth": base.get("goal_kind"),
            "plan_termination_at_shipped_depth": base_term,
        }
        (conversions if base_term == "depth_capped" else non_attributable).append(rec)
        break
report["conversions_depth_attributable"] = conversions
report["converted_but_not_depth_attributable"] = non_attributable

# ---- 4. cost ---------------------------------------------------------------------------
cost = {}
for d in depths:
    rows = [r for r in raw["results"] if r["_depth"] == d and r.get("status") == "ok"]
    if not rows:
        continue
    cost[str(d)] = {
        "n": len(rows),
        "mean_goal_wall_s": round(sum(r.get("goal_wall_s", 0) for r in rows) / len(rows), 3),
        "mean_plan_wall_s": round(sum(r.get("plan_wall_s", 0) for r in rows) / len(rows), 3),
        "max_plan_wall_s": round(max(r.get("plan_wall_s", 0) for r in rows), 3),
        "goal_kinds": dict(Counter(str(r.get("goal_kind")) for r in rows)),
    }
report["cost"] = cost

# ---- verdict + checksum ----------------------------------------------------------------
# The verdict is DERIVED from the numbers, never hand-written: a hand-written "confirmed" can
# outlive the measurement that justified it, which is the exact drift this project's corrigenda
# keep recording. Terminal prefix per the Verdict Terminal-Prefix Discipline.
_filled = [d for d in depths if per_depth[str(d)]["n_INTERSECTION"] > 0]
if conversions and _filled:
    report["honest_verdict"] = (
        f"complete_depth_cap_was_the_binding_constraint_intersection_fills_at_depth_{min(_filled)}"
    )
else:
    report["honest_verdict"] = (
        "complete_raising_max_depth_does_not_fill_the_intersection_selection_conflict_is_real"
    )
report["first_depth_with_nonempty_intersection"] = min(_filled) if _filled else None
if _filled:
    _floor = min(_filled)
    _at_or_above = {per_depth[str(d)]["n_INTERSECTION"] for d in depths if d >= _floor}
    report["intersection_saturates"] = len(_at_or_above) == 1
else:
    report["intersection_saturates"] = None

# Content hash over the INPUTS and the derived findings, so a reader can tell a re-run that
# reproduced from a re-run that drifted. Computed over the sorted raw results rather than the
# report dict, because the report embeds wall-times that legitimately vary between runs.
_digest_src = json.dumps(
    sorted(
        (
            r["_key"],
            r["_depth"],
            r.get("status"),
            r.get("goal_satisfiable"),
            r.get("goal_kind"),
            r.get("plan_found"),
            r.get("plan_length"),
        )
        for r in raw["results"]
    ),
    sort_keys=True,
)
report["reproducibility_checksum"] = hashlib.sha256(_digest_src.encode()).hexdigest()
report["reproducibility_checksum_covers"] = (
    "the (candidate, depth) -> (status, goal_satisfiable, goal_kind, plan_found, plan_length) "
    "map only. Wall-times are deliberately EXCLUDED: they vary run to run and would make an "
    "otherwise-exact reproduction report as drifted."
)

(OUT_DIR / "depth_sweep_scored.json").write_text(json.dumps(report, indent=1))

print("=== CONTROL: mismatches vs best-of-N at depth 40 ===")
print(f"  {len(mismatch)} (expected exactly 1: ft09|5, explained)")
print("\n=== STALL PATH: the intersection ===")
print(f"{'depth':>6} {'(i)':>5} {'plan':>5} {'BOTH':>5}")
for d in depths:
    v = per_depth[str(d)]
    print(f"{d:>6} {v['n_criterion_i']:>5} {v['n_plan_found']:>5} {v['n_INTERSECTION']:>5}")
print("\n=== DEPTH-ATTRIBUTABLE CONVERSIONS ===")
for c in conversions:
    print(
        f"  {c['game']}|k{c['candidate']}  first plans at depth {c['first_depth_that_plans']}"
        f"  len={c['plan_length']} nodes={c['nodes_expanded']}"
        f"  (i)={c['criterion_i']} strict={c['criterion_i_strict']}"
        f" shipped_gate={c['shipped_gate_passes']}"
    )
if not conversions:
    print("  NONE -- the intersection stays empty; depth was not the binding constraint.")
if non_attributable:
    print("\n=== converted but NOT depth-attributable (excluded from headline) ===")
    for c in non_attributable:
        _term = c["plan_termination_at_shipped_depth"]
        print(f"  {c['game']}|k{c['candidate']}  term_at_40={_term}")
print("\n=== COST ===")
for d in depths:
    if str(d) in cost:
        v = cost[str(d)]
        print(f"  depth {d:>3}: mean plan {v['mean_plan_wall_s']}s  max {v['max_plan_wall_s']}s")
print(f"\nwrote {OUT_DIR / 'depth_sweep_scored.json'}")
