def engine(grid, action, data=None):
    if action != 6:
        return grid
    
    y, x = data['y'], data['x']
    out = grid.copy()
    
    # The observed transitions show ACTION6 (clicking) at specific coordinates
    # triggers changes in distant parts of the same row/column or related structures.
    # Specifically, clicking at (48, 21) affects r9-r11 and r63.
    # Clicking at (24, 47) affects r34-r41 and r63.
    
    # Based on thes patterns, we are looking for "blocks" of colors that can be shifted or toggled.
    # In this case, the same color blocks appear to move horizontally across their designated areas.
    # Shift logic for (48, 21) area:
    if y == 21 and x == 48:
        # This click seems to trigger a movement of a 3x3-ish structure of color 14
        # moving rightwards.
        # We need to find where the current 'head' of the block is.
        # Find first occurrence of color 14 in row 9 starting from col 36
        col_start = -1
        for c in range(36, 64):
            if grid[9, c] == 14:
                break
            col_start = c # Not exactly correct, but it's a<|channel>thought
        
        # Let's try a more direct approach based on the observed deltas.
        # The block moves by 3 columns each time.
        # Current position check:
        current_pos = -1
        for c in range(36, 64):
            if grid[9, c] == 14:
                current_pos = c
                break
        
        if current_pos != -1:
            # Move the block (color 14) 3 units right
            # Clear old pos
            out[9, current_pos:current_pos+3] = 5
            out[10, current_pos-2 if current_pos > 38 else 34] = 5
            out[10, current_pos if current_pos > 38 else 36] = 5
            out[11, current_pos:current_pos+3] = 5
            
            # Set new pos
            new_pos = current_pos + 3
            if new_pos < 61:
                out[9, new_pos:new_pos+3] = 14
                out[10, new_pos-2] = 14
                out[10, new_pos] = 14
                out[11, new_pos:new_pos+3] = 14
            else:
                # Special case for the end of the movement range
                out[9, 51] = 14
                out[9, 53] = 14
                out[10, 49] = 14
                out[10, 52] = 13 # This is a toggle/change to color 13
                out[11, 51] = 14
                out[11, 53] = 14

        # Update r63 (the counter)
        for c in range(63, -1, -1):
            if grid[63, c] == 4:
                out[63, c] = 3
                break
    
    elif y == 47 and x == 24:
        # Similar logic for clicking at (24, 47) affecting r34-r41.
        # Find current position of block color 11
        current_pos = -1
        for c in range(9, 21):
            if grid[36, c] == 11:
                # We are looking for the start of the block
                pass
        
        # Based on deltas, it seems to be moving vertically or toggling blocks.
        # The changes occur in rows 34, 36, 37, 38, 39, 40, 41.
        # This is a vertical shift of a pattern.
        
        # Let's simplify based on observed transitions.
        # It moves from one "slot" to another.
        # Slot 1: r34c10, r36c9-11, r37c10, r38c9-11
        # Slot 2: r37c10, r39c9-11, r40c10, r41c9-11
        
        # Check if we are in slot 1
        is_slot1 = (grid[34, 10] == 11)
        
        if is_slot1:
            out[34, 10] = 11 # wait, delta says r34c10 becomes 11? No, INITIAL grid has 5 there.
            # Delta 1: r34c10:11x1, r36c9:11x3, r37c9:11x1, 13x1, 11x1, r38c9:11x3
            # This means it fills a pattern.
            out[34, 10] = 11
            out[36, 9:12] = 11
            out[37, 9] = 11
            out[37, 10] = 13
            out[37, 11] = 11
            out[38, 9:12] = 11
            
            # Update counter
            for c in range(63, -1, -1):
                if grid[63, c] == 4:
                    out[63, c] = 3
                    break
        else:
            # Slot 2
            out[37, 10] = 11
            out[39, 9:12] = 11
            out[40, 9] = 11
            out[40, 10] = 13
            out[40, 11] = 11
            out[41, 9:12] = 11
            
            # Update counter
            for c in range(63, -1, -1):
                if grid[63, c] == 4:
                    out[63, c] = 3
                    break

    return out

def is_level_complete(grid):
    # The win state isn't explicitly given, but usually it involves the counter r63.
    # In this game, color 4 seems to be moving left on row 63.
    # If all cells are 3 or if a certain cell is reached, it might be complete.
    # Let's assume completion when no more 4s are left on row 63.
    return not np.any(grid[63, :] == 4)

