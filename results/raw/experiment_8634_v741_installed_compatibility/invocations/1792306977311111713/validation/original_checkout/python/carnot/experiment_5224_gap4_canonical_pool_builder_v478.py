@dataclass(frozen=True)
class GenerationCertificate:
    """Evidence from the local SOTA GGUF call that seeds constrained rows."""

    model_id: str
    model_path_or_digest: str
    started_at: str
    duration_s: float
    completion_text: str
    random_seed: int
    backend: str


def _stable_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), default=str)


def _sha256_text(text: str) -> str:
    return "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()


def payload_checksum(artifact: Mapping[str, Any]) -> str:
    payload = json.loads(json.dumps(dict(artifact), sort_keys=True, default=str))
    payload["reproducibility_checksum"] = ""
    return _sha256_text(_stable_json(payload))


def _read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


def _write_json_atomic(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(dict(payload), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, path)


def _utc_now() -> str:  # pragma: no cover - exercised through injected certificates.
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _candidate_rows(payload: Any) -> list[JsonDict]:
    if not isinstance(payload, Mapping):
        return []
    rows = payload.get("candidate_rows")
    if not isinstance(rows, list):
        rows = payload.get("events")
    if not isinstance(rows, list):
        return []
    return [dict(row) for row in rows if isinstance(row, Mapping)]


def _load_exp5223_audit(root: Path) -> JsonDict:
    payload = _read_json(root / exp5223.RESULT_RELATIVE_PATH)
    return dict(payload) if isinstance(payload, Mapping) else {}


def _load_canonical_schema(root: Path) -> JsonDict:
    path = root / exp5223.CANONICAL_SCHEMA_RELATIVE_PATH
    payload = _read_json(path)
    if not isinstance(payload, Mapping) or "required" not in payload:
        raise ValueError(f"canonical schema missing or malformed: {path}")
    return dict(payload)


def _dedupe_rows(rows: Sequence[Mapping[str, Any]]) -> list[JsonDict]:
    out: list[JsonDict] = []
    seen: set[str] = set()
    for row in rows:
        candidate_id = str(row.get("candidate_id") or "")
        if not candidate_id or candidate_id in seen:
            continue
        seen.add(candidate_id)
        out.append(dict(row))
    return out


def repair_rows_from_sources(root: Path, audit: Mapping[str, Any]) -> list[JsonDict]:
    """Recover only already-canonical rows when Exp 5223 says repair is allowed."""

    if audit.get("gap4_pool_repairable") is not True:
        return []
    repaired: list[JsonDict] = []
    for relative in (exp5223.EXP5211_RELATIVE_PATH, exp5223.EXP5211_CHECKPOINT_RELATIVE_PATH):
        for row in _candidate_rows(_read_json(root / relative)):
            if exp5223.canonical_candidate_record_errors(row):
                continue
            repaired.append(dict(row))
    return _dedupe_rows(repaired)


