_BG = np.array([[int(ch, 16) for ch in row] for row in _BG_ROWS], dtype=np.int64)
_PLUS_CELLS = ((52, 10), (53, 9), (53, 10), (53, 11), (54, 10))  # (row, col) of the plus's colour-0 pixels
_WIN_BOX = (44, 11, 52, 19)  # 9-shaped goal sprite at (44, 11), 9x9: block centre inside -> level up


def _find_block(g):
    """Top-left (x, y) of the 3x3 colour-15 block in the play field (y >= 10), or None."""
    for y in range(10, 62):
        for x in range(0, 62):
            if y <= 60:
                if (g[y:y + 3, x:x + 3] == 15).all():
                    return x, y
            elif (g[y:y + 2, x:x + 3] == 15).all():  # y == 61: row 63 may be hidden by the step bar
                return x, y
    return None


def _render(block, plus_visible, steps_left):
    out = _BG.copy()
    if block is not None:
        bx, by = block
        out[by:by + 3, bx:bx + 3] = 15
    if plus_visible:
        for r, c in _PLUS_CELLS:
            out[r, c] = 0
    out[63, 0:2 * steps_left] = 0
    return out


def engine(grid, action, data):
    g = np.array(grid)
    if g.shape != (64, 64):
        return g.copy()
    if int(action) != 6 or data is None:
        return g.copy()  # ACTION7 undo: hidden history -> best grid-only guess is no change
    x = int(data.get("x", 0))
    y = int(data.get("y", 0))
    if not (0 <= x < 64 and 0 <= y < 64):
        return g.copy()
    row63 = g[63]
    nz = np.nonzero(row63 != 0)[0]
    lead = int(nz[0]) if nz.size else 64
    steps_left = lead // 2
    if steps_left <= 0:
        return g.copy()
    plus_visible = all(int(g[r, c]) == 0 for r, c in _PLUS_CELLS)
    if plus_visible and 8 <= x <= 11 and 52 <= y <= 55:
        plus_visible = False
    if y <= 9 or y >= 63:
        return g.copy()  # outside the play field: no move, no step spent (Su15.axaxyjxqoe)
    block = _find_block(g)
    if block is not None:
        bx, by = block
        nx = min(max(x, bx), bx + 2)
        ny = min(max(y, by), by + 2)
        if (x - nx) ** 2 + (y - ny) ** 2 <= 64:
            for _ in range(4):
                dx = x - (bx + 1)
                dy = y - (by + 1)
                bx = min(max(bx + max(-4, min(4, dx)), 0), 61)
                by = min(max(by + max(-4, min(4, dy)), 10), 61)
            block = (bx, by)
    if block is not None and block != (3, 58):
        plus_visible = False
    return _render(block, plus_visible, steps_left - 1)


def is_level_complete(grid):
    g = np.asarray(grid)
    if g.shape != (64, 64):
        return False
    b = _find_block(g)
    if b is None:
        return False
    cx, cy = b[0] + 1, b[1] + 1
    x0, y0, x1, y1 = _WIN_BOX
    return x0 <= cx <= x1 and y0 <= cy <= y1
